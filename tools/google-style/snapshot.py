"""
Snapshot of the Google developer documentation style guide (https://developers.google.com/style, CC BY 4.0) for the
docstyle Google layer: every page as Markdown in mcp/docstyle/layers/google/source/, with its URL, fetch date and a
content hash, plus an index. Re-run to update; `git diff` on the source folder shows what Google changed.

Also writes source/units.json: every paragraph, list item, table row and example of every page with a stable id
(page#n + hash). Compiled rule cards cite these units; the coverage report fails on any unit that no card covers and
that isn't marked not-applicable.

    uv run --script tools/google-style/snapshot.py
"""
import datetime
import hashlib
import json
import re
import sys
import time
import urllib.request
from pathlib import Path

from bs4 import BeautifulSoup
from markdownify import markdownify

BASE = "https://developers.google.com"
OUT = Path(__file__).resolve().parent / "source"
UA = {"User-Agent": "FlareAI-docstyle-snapshot/1.0 (style guide layer; CC BY 4.0 attribution kept)"}


def get(url):
    for attempt in range(3):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                return r.read().decode("utf-8")
        except Exception:
            if attempt == 2:
                raise
            time.sleep(2 + attempt * 3)


def pages():
    """Every page in the guide's left navigation, in order, with its section."""
    soup = BeautifulSoup(get(BASE + "/style"), "html.parser")
    nav = soup.select_one("devsite-book-nav") or soup
    seen, out, section = set(), [], ""
    for el in nav.find_all(["li", "a"]):
        if el.name == "li" and "devsite-nav-heading" in (el.get("class") or []):
            section = el.get_text(" ", strip=True)
        if el.name == "a":
            href = (el.get("href") or "").split("#")[0].split("?")[0]
            if href.startswith(BASE):
                href = href[len(BASE):]
            if href.startswith("/style") and href not in seen:
                seen.add(href)
                out.append({"path": href, "title": el.get_text(" ", strip=True), "section": section})
    return out


def article(html):
    soup = BeautifulSoup(html, "html.parser")
    body = soup.select_one(".devsite-article-body") or soup.select_one("article")
    # The "Page Summary" panel is generated by AI on Google's side, not part of the guide: never a source of rules.
    for junk in body.select("devsite-key-takeaways-panel, devsite-feedback, devsite-thumb-rating, .devsite-article-meta, script, style, devsite-toc, .nocontent"):
        junk.decompose()
    title = (soup.select_one("h1.devsite-page-title") or soup.select_one("h1"))
    return (title.get_text(" ", strip=True) if title else ""), body


def units(slug, body):
    """Reviewable pieces of a page: paragraphs, list items, table rows, preformatted examples."""
    out, heading = [], ""
    for el in body.find_all(["h2", "h3", "h4", "p", "li", "tr", "pre", "dt"]):
        if el.name in ("h2", "h3", "h4"):
            heading = el.get_text(" ", strip=True)
            continue
        if el.name == "p" and el.find_parent(["li", "td", "th"]):
            continue          # counted with its list item / row
        if el.name == "dt":
            # Word list: the term and every definition under it are one unit ("& (ampersand): Don't use & instead of and…").
            defs, sib = [], el.find_next_sibling()
            while sib is not None and sib.name == "dd":
                defs.append(sib.get_text(" ", strip=True))
                sib = sib.find_next_sibling()
            text = el.get_text(" ", strip=True) + ": " + " ".join(defs)
        elif el.name in ("p", "li") and el.find_parent("dd"):
            continue
        elif el.name == "li" and el.find("li"):
            text = " ".join(t for t in el.find_all(string=True, recursive=False)).strip() or el.contents[0].get_text(" ", strip=True) if el.contents else ""
        else:
            text = el.get_text(" ", strip=True)
        text = re.sub(r"\s+", " ", text)
        if len(text) < 3:
            continue
        n = len(out) + 1
        out.append({"id": f"{slug}#{n}", "hash": hashlib.sha1(text.encode()).hexdigest()[:10], "kind": el.name,
                    "heading": heading, "text": text})
    return out


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    today = datetime.date.today().isoformat()
    index, all_units = [], {}
    for p in pages():
        slug = p["path"].strip("/").replace("style/", "", 1).replace("/", "-") if p["path"] != "/style" else "about"
        url = BASE + p["path"]
        try:
            title, body = article(get(url))
        except Exception as e:
            print("FAILED", url, e, file=sys.stderr)
            continue
        md = markdownify(str(body), heading_style="ATX", bullets="-").strip()
        md = re.sub(r" ?\[link\]\(#[^)]*\)", "", md)
        md = re.sub(r"\n{3,}", "\n\n", md)
        title = p["title"] or title
        digest = hashlib.sha256(md.encode()).hexdigest()[:16]
        header = (f"---\ntitle: {json.dumps(title)}\nsection: {json.dumps(p['section'])}\nurl: {url}\n"
                  f"fetched: {today}\nsha256: {digest}\nlicense: CC BY 4.0, Google LLC (https://developers.google.com/style)\n---\n\n")
        (OUT / f"{slug}.md").write_text(header + md + "\n", encoding="utf-8")
        u = units(slug, body)
        all_units[slug] = u
        index.append({"slug": slug, "title": title, "section": p["section"], "url": url, "sha256": digest,
                      "words": len(md.split()), "units": len(u)})
        print(f"{slug:40} {len(md.split()):6} words {len(u):4} units")
        time.sleep(0.5)
    (OUT / "index.json").write_text(json.dumps({"fetched": today, "source": BASE + "/style", "license": "CC BY 4.0",
                                                "pages": index}, indent=1), encoding="utf-8")
    (OUT / "units.json").write_text(json.dumps(all_units, indent=1, ensure_ascii=False), encoding="utf-8")
    words = sum(p["words"] for p in index)
    print(f"\n{len(index)} pages, {words} words (~{int(words * 1.35)} tokens), {sum(p['units'] for p in index)} units -> {OUT}")


if __name__ == "__main__":
    main()
